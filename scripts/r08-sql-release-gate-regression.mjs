import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const sql = readFileSync('supabase/proposals/20260912_controlled_beta_boundaries.sql','utf8');
const functions = [...sql.matchAll(/create or replace function public\.(\w+)\((.*?)\)\s*([\s\S]*?)as \$\$([\s\S]*?)\$\$;/gs)];
assert.equal(functions.length,4);
const find = (name) => { const fn = functions.find((f) => f[1] === name); assert.ok(fn,name); return fn; };
const create = find('create_or_resume_competency_application_draft');
assert.match(create[2], /p_dealer_id uuid, p_client_id uuid, p_values jsonb/);
assert.match(create[3], /returns public.application_cases/); assert.match(create[3], /security invoker/);
assert.match(create[4], /auth.uid\(\) is null/);
assert.match(create[4], /for update/); assert.match(create[4], /transaction_isolation/);
assert.match(create[4], /order by created_at, id limit 1/);
assert.ok(create[4].indexOf('Competency is not available') < create[4].indexOf('if found then return v_case'));
const guard = find('guard_beta_record_removal');
assert.match(guard[3], /security definer/); assert.match(guard[3], /set search_path = pg_catalog, public, pg_temp/);
assert.match(guard[3], /set row_security = off/); assert.match(guard[3], /lock_timeout/);
assert.match(guard[4], /TG_TABLE_SCHEMA <> 'public'/);
assert.match(guard[4], /role in \('owner', 'administrator'\)/);
assert.match(guard[4], /public.audit_log where entity_id = old.id/);
assert.match(guard[4], /applicationCaseIds/);
assert.match(guard[4], /pg_constraint/); assert.match(guard[4], /confkey\[1\]/);
assert.match(guard[4], /lock table public.audit_log, public.documents in share mode/);
// Privilege elevation is exclusively a protection check; it cannot issue DML.
assert.doesNotMatch(guard[4], /\b(insert into|update public\.|delete from|truncate|alter table|grant)\b/i);
assert.match(sql, /revoke all on function public.guard_beta_record_removal\(\) from public, anon, authenticated/);
assert.equal((sql.match(/security definer/gi) ?? []).length, 1);
assert.equal((sql.match(/create or replace trigger /gi) ?? []).length,5);
assert.doesNotMatch(sql, /(?<!replace )create trigger /i);
const startGuard = find('guard_competency_draft_start')[4];
assert.match(startGuard, /old.status::text in \('SUBMITTED', 'APPROVED', 'DECLINED', 'WITHDRAWN', 'CLOSED'\)/);
assert.match(startGuard, /new.competency_id[\s\S]*dealer_id = new.dealer_id and client_id = new.client_id/);
const remove = find('remove_safe_beta_record');
assert.match(remove[2], /p_table text, p_id uuid, p_dealer_id uuid/);
assert.match(remove[3], /returns boolean language plpgsql security invoker/);
assert.match(remove[4], /where id = \$1 and dealer_id = \$2/);
assert.match(remove[4], /v_count <> 1/);
assert.match(sql, /Required competency application enum values are missing/);
assert.doesNotMatch(sql, /alter type|drop table|drop column|create policy|disable row level security/i);
const caseService = readFileSync('src/services/applicationCaseService.ts','utf8');
const deleteService = readFileSync('src/services/safeDeletionService.ts','utf8');
assert.match(caseService, /rpc\('create_or_resume_competency_application_draft', \{\s*p_dealer_id: dealerId, p_client_id: clientId, p_values:/);
assert.match(deleteService, /rpc\('remove_safe_beta_record', \{\s*p_table: table, p_id: id, p_dealer_id: dealerId/);
assert.equal(createHash('sha256').update(readFileSync('supabase/migrations/20260906_firearm_application_drafts.sql')).digest('hex'), 'f7ab53e679736bed76bfb562dbd2bfd874c67b1828a1cd3cfb5a1fe037e459c3');
console.log('R08 static SQL/client gate checks passed; this does not execute SQL or certify live schema compatibility.');
